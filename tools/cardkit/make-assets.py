#!/usr/bin/env python3
"""The provisioner's load files, written from the CAPs, or checked against them.

    python3 tools/cardkit/make-assets.py [--cap PATH] [--hello-cap PATH] [--check]

A load file is what gp sends after INSTALL [for load]: C4, its BER length, then
the components refcheck counts, in refcheck's order (tools/refcheck.py, LOADED
and components; GlobalPlatformPro's CAPFile.getCode sends the same). The card's
comes from the tracked CAP, applet/target/cashu-javacard-2.1.0.cap (its sha256
is published in docs/HARDWARE_DEPLOYMENT.md, and pinned below as CAP_SHA256),
and must be the 20,068 bytes refcheck measures, with the sha256 pinned below as
LOAD_FILE_SHA256: the provisioner checks that hash again before it sends a
byte. The hello applet's comes from `ant -f applet/build.xml hello-cap`.

The output is TypeScript, the load file in hex (.gitignore keeps *.cap out of
the repo), in apps/provisioner/src/assets/cashu.ts and hello.ts. --check writes
nothing, and fails if either file is not exactly what the CAPs give. In CI the
tracked CAP has been moved aside before the build overwrites its path, so the
cap job passes it with --cap.
"""
import argparse
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from refcheck import LOADED, components  # noqa: E402

CAP = 'applet/target/cashu-javacard-2.1.0.cap'
HELLO_CAP = 'applet/target/hello-1.0.cap'
CAP_SHA256 = 'f27d92ba99581f4e42abda0efc038b2c31128f9b405bcec6de52f6a12ae4c7e5'
LOAD_FILE_SHA256 = 'fe7d8ac31be1284f8a9a6d031cdee9b4690f8d02e0a9ab1fa3bac645f6bc13ee'
LOAD_FILE_SIZE = 20068
ASSETS = 'apps/provisioner/src/assets'


def load_file(path):
    """C4, the BER length of the components, and the components in refcheck's order."""
    parts = components(path)
    body = b''.join(parts[k] for k in LOADED if k in parts)
    n = len(body)
    if n < 0x80:
        head = bytes([0xC4, n])
    elif n < 0x100:
        head = bytes([0xC4, 0x81, n])
    elif n < 0x10000:
        head = bytes([0xC4, 0x82, n >> 8, n & 0xFF])
    else:
        raise SystemExit('make-assets: %s has %d bytes of components, more than a load file of this kind holds' % (path, n))
    return head + body


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def render(const, name, cap_rel, cap_sha, data):
    source = ('// (sha256 %s). Do not edit: run the script; CI runs it with --check.\n' % cap_sha if cap_sha else
              '// (rebuilt by ant hello-cap: the CAP\'s own hash moves with the converter\'s timestamp,\n'
              '// the load file\'s below does not). Do not edit: run the script; CI runs it with --check.\n')
    return ''.join([
        '// Generated by tools/cardkit/make-assets.py from %s\n' % cap_rel,
        source,
        '// The load file gp sends after INSTALL [for load]: C4, its length, then the\n',
        '// components tools/refcheck.py counts, in its order.\n',
        '\n',
        'export const %s = {\n' % const,
        "  name: '%s',\n" % name,
        "  capSha256: '%s',\n" % cap_sha if cap_sha else '',
        '  size: %d,\n' % len(data),
        "  sha256: '%s',\n" % sha256(data),
        "  hex: '%s',\n" % data.hex().upper(),
        '};\n',
    ])


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--cap', default=os.path.join(ROOT, CAP), help='the card CAP (default: the tracked one)')
    parser.add_argument('--hello-cap', default=os.path.join(ROOT, HELLO_CAP), help='the hello CAP (default: what ant hello-cap writes)')
    parser.add_argument('--check', action='store_true', help='write nothing; fail if the assets differ')
    args = parser.parse_args(argv[1:])

    with open(args.cap, 'rb') as f:
        cap_sha = sha256(f.read())
    if cap_sha != CAP_SHA256:
        print('make-assets: %s has sha256 %s, not CAP_SHA256 %s in tools/cardkit/make-assets.py'
              ' (a new CAP moves it, with LOAD_FILE_SIZE and LOAD_FILE_SHA256)' % (args.cap, cap_sha, CAP_SHA256))
        return 1
    cashu = load_file(args.cap)
    if len(cashu) != LOAD_FILE_SIZE or sha256(cashu) != LOAD_FILE_SHA256:
        print('make-assets: the card\'s load file is %d bytes, sha256 %s; LOAD_FILE_SIZE and LOAD_FILE_SHA256'
              ' in tools/cardkit/make-assets.py say %d, %s' % (len(cashu), sha256(cashu), LOAD_FILE_SIZE, LOAD_FILE_SHA256))
        return 1

    if not os.path.exists(args.hello_cap):
        print('make-assets: no %s: build it with  ant -f applet/build.xml hello-cap' % args.hello_cap)
        return 1
    hello = load_file(args.hello_cap)

    out = {
        'cashu.ts': render('CASHU_LOAD_FILE', 'cashu-javacard 2.1.0', CAP, CAP_SHA256, cashu),
        'hello.ts': render('HELLO_LOAD_FILE', 'hello 1.0', HELLO_CAP, None, hello),
    }
    failed = False
    for name, text in out.items():
        path = os.path.join(ROOT, ASSETS, name)
        if args.check:
            try:
                with open(path, encoding='utf-8') as f:
                    same = f.read() == text
            except FileNotFoundError:
                same = False
            print('%s %s' % ('ok  ' if same else 'DIFF', os.path.relpath(path, ROOT)))
            failed |= not same
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            print('wrote %s' % os.path.relpath(path, ROOT))
    if failed:
        print('make-assets: the assets are not what the CAPs give: run  python3 tools/cardkit/make-assets.py  and commit the result')
        return 1
    print('card load file %d bytes, sha256 %s; hello load file %d bytes, sha256 %s' % (len(cashu), sha256(cashu), len(hello), sha256(hello)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
